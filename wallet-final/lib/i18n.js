const DICTIONARIES = { fr, en, es, de, pt };

// Intl locale tag utilisé pour les dates formatées dans l'UI (toLocaleDateString) —
// pour l'instant seulement l'accueil (sparkline, actus) ; le reste de l'app
// (Stats, documents légaux...) reste en 'fr-FR' pour cette phase.
const INTL_LOCALE_TAG = { fr: 'fr-FR', en: 'en-US', es: 'es-ES', de: 'de-DE', pt: 'pt-PT' };

// Lecture d'une entree PROPRE a l'objet : sans ce garde-fou, une cle comme
// "toString" ou "constructor" etait lue sur le prototype et translate()
// renvoyait une fonction au lieu d'un texte.
const own = (obj, k) => (Object.prototype.hasOwnProperty.call(obj, k) ? obj[k] : undefined);

function translate(locale, key, vars) {
  const dict = own(DICTIONARIES, locale) || DICTIONARIES.fr;
  // Hors français, une clé pas encore traduite (es/de/pt sont partiels)
  // retombe d'abord sur l'anglais : pour un visiteur étranger, un texte en
  // anglais reste lisible, un texte en français non.
  const englishFallback = locale === 'fr' ? undefined : own(DICTIONARIES.en, key);
  let text = own(dict, key) ?? englishFallback ?? own(DICTIONARIES.fr, key) ?? key;
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      // Fonction de remplacement (et non la valeur directement) : sinon un
      // "$&", "$$" ou "$'" dans la valeur (ex. nom de token choisi par son
      // createur) serait interprete comme un motif de String.replace.
      text = text.replace(new RegExp(`{{${k}}}`, 'g'), () => String(v));
    }
  }
  return text;
}

const SUPPORTED_LOCALES = ['fr', 'en', 'es', 'de', 'pt'];

// Langue de départ d'un visiteur qui n'a encore rien choisi dans Paramètres :
// français si l'appareil est réglé en français, anglais sinon. Seules ces deux
// langues couvrent tout le parcours d'un nouveau visiteur ; es/de/pt restent
// proposés dans Paramètres. Avant, tout le monde démarrait en français, et un
// visiteur venu de Product Hunt tombait sur une page qu'il ne pouvait pas lire.
function detectDeviceLocale() {
  try {
    const nav = typeof navigator !== 'undefined' ? navigator : null;
    let tag = nav && ((nav.languages && nav.languages[0]) || nav.language);
    if (!tag && typeof Intl !== 'undefined') tag = Intl.DateTimeFormat().resolvedOptions().locale;
    if (!tag) return 'fr';
    return String(tag).toLowerCase().startsWith('fr') ? 'fr' : 'en';
  } catch {
    return 'fr';
  }
}

module.exports = { translate, SUPPORTED_LOCALES, INTL_LOCALE_TAG, detectDeviceLocale, DICTIONARIES };
